st = collections.Counter(c["status"] for c in checks)
tot = len(checks)
ex = st["Passed"] + st["Failed"]
cls = collections.Counter(b["class"] for b in bugs)
sev = collections.Counter(b["severity"] for b in bugs)
CLS_RU = {"validation-missing": "Нет валидации: сервер принял невалидный запрос (200 вместо 4xx)", "unhandled-500": "Необработанная ошибка: 500 вместо 400", "incomplete-response": "Неполное тело ответа", "wrong-status": "Неверный код ответа"}
SEV_RU = {"high": "High", "medium": "Medium", "low": "Low"}
ICON = {"Passed": "✅", "Failed": "❌", "Skipped": "⏭"}
html500 = sum(1 for b in bugs if b["actual_status"] == 500 and "<!DOCTYPE" in b["actual"])
leak = sum(1 for b in bugs if b["leak"])


def w(path, text):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


def short(s, n=110):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1] + "…"


def code(b, lang):
    return f"```{lang}\n{b.strip()}\n```"


# ---------- README
by_ep = collections.OrderedDict()
for c in checks:
    by_ep.setdefault(c["endpoint"], []).append(c)
